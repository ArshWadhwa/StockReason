    # ── Sentiment (from M2 parquet) ────────────────────────────────────
    def _load_sentiment(self):
        """Load sentiment from M2 sentiment_features.parquet."""
        import pandas as pd
        sent_path = PROCESSED_DIR / "sentiment_features.parquet"
        if not sent_path.exists():
            logger.warning("sentiment_features.parquet not found!")
            return

        df = pd.read_parquet(sent_path)
        df['date'] = pd.to_datetime(df['date'])

        for ticker, grp in df.groupby('ticker'):
            grp = grp.sort_values('date')
            if grp.empty:
                continue

            latest = grp.iloc[-1]
            avg_score = float(latest.get('sentiment_mean', 0.0))

            # Determine label
            if avg_score > 0.15:
                label = "bullish"
            elif avg_score < -0.15:
                label = "bearish"
            else:
                label = "neutral"

            # Divergence
            div_flag = int(latest.get('sentiment_divergence_flag', 0))
            div_desc = str(latest.get('divergence_desc', ''))

            # Build headlines from all sentiment entries for this ticker
            headlines = []
            for idx, row in grp.iterrows():
                dt = row['date'].strftime('%Y-%m-%dT%H:%M:%S') if hasattr(row['date'], 'strftime') else str(row['date'])
                score = float(row.get('sentiment_mean', 0.0))
                h_label = 'positive' if score > 0.1 else ('negative' if score < -0.1 else 'neutral')
                headlines.append({
                    "id": f"{ticker}_{dt[:10]}",
                    "headline": f"{STOCK_META.get(ticker, {}).get('name', ticker)} sentiment report for {dt[:10]}"
                                f" — score: {score:+.2f}",
                    "source": "FinBERT / RSS Pipeline",
                    "published_at": dt,
                    "sentiment_score": round(score, 4),
                    "sentiment_label": h_label,
                    "confidence": round(abs(score), 2),
                })

            self.sentiment[ticker] = {
                "ticker": ticker,
                "avg_sentiment_score": round(avg_score, 4),
                "sentiment_label": label,
                "article_count": int(latest.get('news_count', len(grp))),
                "bullish_ratio": round(float(latest.get('sentiment_pos_ratio', 0.0)), 4),
                "bearish_ratio": round(float(latest.get('sentiment_neg_ratio', 0.0)), 4),
                "divergence_alert": {
                    "has_divergence": div_flag != 0,
                    "message": div_desc if div_desc else (
                        "Normal: Price and sentiment are aligned"
                        if div_flag == 0
                        else "Divergence detected between price action and news sentiment"
                    ),
                },
                "headlines": headlines[-10:],  # Last 10
            }

    # ── Signal Generation (real-time from predictions + sentiment) ─────
    def _generate_signals(self):
        """Generate signals from real predictions using RuleBasedSignalEngine."""
        from src.m4_dashboard.backend.signal_engine import RuleBasedSignalEngine
        engine = RuleBasedSignalEngine()

        for ticker, pred in self.predictions.items():
            price_data = self.prices.get(ticker)
            sent_data = self.sentiment.get(ticker)
            if not price_data:
                continue

            horizons = pred.get('horizons', {})
            h_1m = horizons.get('1M', {})
            ensemble = pred.get('ensemble', {})
            current_price = price_data['current_price']

            # Get latest technical indicators from price history
            latest_hist = price_data['history'][-1] if price_data['history'] else {}
            sma_50 = latest_hist.get('sma_50')
            rsi_14 = latest_hist.get('rsi_14')
            regime = latest_hist.get('regime', 'trending')

            sentiment_score = sent_data['avg_sentiment_score'] if sent_data else 0.0

            signal = engine.evaluate(
                ticker=ticker,
                current_price=current_price,
                expected_return_1M=h_1m.get('expected_return', 0.0),
                confidence=h_1m.get('confidence', 0.5),
                sentiment_score=sentiment_score,
                regime=regime,
                lstm_return_1M=ensemble.get('lstm_return_1M'),
                xgboost_return_1M=ensemble.get('xgboost_return_1M'),
                sma_50=sma_50,
                rsi_14=rsi_14,
                metadata=STOCK_META.get(ticker, {"name": ticker, "sector": "Unknown", "universe": "NIFTY 50"}),
            )
            self.signals[ticker] = signal

