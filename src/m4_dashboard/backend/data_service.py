    # ── Price Data (from M1 parquet + live Yahoo Finance) ──────────────
    def _load_prices(self):
        """Load price history from M1 price_features.parquet and fetch live prices."""
        import pandas as pd
        price_path = PROCESSED_DIR / "price_features.parquet"
        if not price_path.exists():
            logger.warning("price_features.parquet not found!")
            return

        df = pd.read_parquet(price_path)
        df['date'] = pd.to_datetime(df['date'])

        # Fetch live prices from Yahoo Finance for accurate current price
        live_prices = self._fetch_live_prices(list(df['ticker'].unique()))

        for ticker, grp in df.groupby('ticker'):
            grp = grp.sort_values('date')
            if grp.empty:
                continue

            meta = STOCK_META.get(ticker, {"name": ticker, "sector": "Unknown", "universe": "NIFTY 50"})

            # Use live price if available, otherwise use latest close from parquet
            latest_row = grp.iloc[-1]
            live = live_prices.get(ticker, {})
            current_price = live.get('price', float(latest_row['close']))
            prev_close = float(grp.iloc[-2]['close']) if len(grp) >= 2 else current_price
            day_change = round(((current_price - prev_close) / prev_close) * 100, 2) if prev_close else 0.0

            # Build history
            history = []
            for _, row in grp.iterrows():
                dt_str = row['date'].strftime('%Y-%m-%d') if hasattr(row['date'], 'strftime') else str(row['date'])[:10]
                history.append({
                    "date": dt_str,
                    "open": round(float(row.get('open', row['close'])), 2),
                    "high": round(float(row.get('high', row['close'])), 2),
                    "low": round(float(row.get('low', row['close'])), 2),
                    "close": round(float(row['close']), 2),
                    "volume": int(row.get('volume', 0)),
                    "sma_20": round(float(row['sma_20']), 2) if 'sma_20' in row and not pd.isna(row['sma_20']) else None,
                    "sma_50": round(float(row['sma_50']), 2) if 'sma_50' in row and not pd.isna(row['sma_50']) else None,
                    "rsi_14": round(float(row['rsi_14']), 2) if 'rsi_14' in row and not pd.isna(row['rsi_14']) else None,
                    "macd": round(float(row.get('macd_line_12_26', 0.0)), 2) if 'macd_line_12_26' in row and not pd.isna(row.get('macd_line_12_26')) else None,
                    "regime": str(row.get('market_regime', 'trending')).lower(),
                })

            self.prices[ticker] = {
                "ticker": ticker,
                "name": meta["name"],
                "sector": meta["sector"],
                "universe": meta["universe"],
                "current_price": round(current_price, 2),
                "day_change_pct": day_change,
                "history": history,
                "live_price_source": "yahoo_finance" if ticker in live_prices else "parquet_latest",
            }

    def _fetch_live_prices(self, tickers: list) -> Dict[str, Dict]:
        """Fetch current prices from Yahoo Finance."""
        live = {}
        try:
            import yfinance as yf
            logger.info(f"Fetching live prices for {len(tickers)} tickers from Yahoo Finance…")
            data = yf.download(tickers, period="2d", group_by='ticker', progress=False, threads=True)
            for ticker in tickers:
                try:
                    if len(tickers) == 1:
                        ticker_data = data
                    else:
                        ticker_data = data[ticker]
                    if not ticker_data.empty:
                        latest = ticker_data.iloc[-1]
                        live[ticker] = {
                            "price": round(float(latest['Close']), 2),
                            "fetched_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                        }
                except Exception:
                    pass
            logger.info(f"Got live prices for {len(live)}/{len(tickers)} tickers")
        except Exception as e:
            logger.warning(f"Yahoo Finance fetch failed: {e}")
        return live

