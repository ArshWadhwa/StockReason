    # ── Daily Digest (computed from real signals) ──────────────────────
    def _compute_digest(self) -> Dict[str, Any]:
        """Generate daily digest from real signals."""
        ranked = self.get_ranked_signals()
        buys = [s for s in ranked if s["signal"] == "BUY"]
        avoids = [s for s in ranked if s["signal"] == "AVOID"]
        holds = [s for s in ranked if s["signal"] == "HOLD"]

        # Market summary from real data
        overview = self.get_market_overview()
        regime = overview.get("market_regime", "unknown")
        n_buy = len(buys)
        n_avoid = len(avoids)
        n_hold = len(holds)
        total = len(ranked)

        market_summary = (
            f"Out of {total} covered stocks, {n_buy} carry BUY signals, "
            f"{n_hold} are HOLD, and {n_avoid} are flagged AVOID. "
            f"Market regime: {regime.replace('_', ' ').title()}. "
            f"Data refreshed at {self.last_refreshed}."
        )

        # Signal upgrades = top BUY signals
        upgrades = []
        for s in buys[:3]:
            reasons = s.get("reasoning", [])
            upgrades.append({
                "ticker": s["ticker"],
                "previous_signal": "HOLD",
                "new_signal": "BUY",
                "primary_catalyst": reasons[0] if reasons else "Strong model conviction",
            })

        # Signal downgrades = AVOID signals
        downgrades = []
        for s in avoids[:3]:
            reasons = s.get("reasoning", [])
            downgrades.append({
                "ticker": s["ticker"],
                "previous_signal": "HOLD",
                "new_signal": "AVOID",
                "primary_catalyst": reasons[0] if reasons else "Negative outlook",
            })

        return {
            "digest_date": datetime.now().strftime("%Y-%m-%d"),
            "market_summary": market_summary,
            "signal_upgrades": upgrades,
            "signal_downgrades": downgrades,
            "top_opportunities": [s["ticker"] for s in buys[:3]],
            "high_risk_alerts": [s["ticker"] for s in avoids[:2]],
        }

    def get_system_status(self) -> Dict[str, Any]:
        """Return system status including last refresh time."""
        return {
            "last_refreshed": self.last_refreshed,
            "tickers_loaded": len(self.prices),
            "predictions_loaded": len(self.predictions),
            "sentiment_loaded": len(self.sentiment),
            "signals_generated": len(self.signals),
            "data_source": "real",
        }
